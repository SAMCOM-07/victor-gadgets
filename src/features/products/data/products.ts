/**
 * Helper to fetch a product by slug
 */
export function getProductBySlug(slug: string): Product | undefined {
  return mockProducts.find((p) => p.slug === slug);
}

/**
 * Helper to get featured products
 */
export function getFeaturedProducts(limit = 8): Product[] {
  return mockProducts.filter((p) => p.isFeatured).slice(0, limit);
}

/**
 * Helper to get hot deals
 */
export function getHotDealProducts(limit = 8): Product[] {
  return mockProducts.filter((p) => p.isHotDeal).slice(0, limit);
}

/**
 * Helper to get products by category
 */
export function getProductsByCategory(category: string): Product[] {
  if (!category || category === "all") return mockProducts;
  return mockProducts.filter((p) => p.category === category);
}

